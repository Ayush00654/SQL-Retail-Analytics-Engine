/* Magnitude Analysis */

/* Find total customers by country */

SELECT
    country,
    COUNT(customer_key) AS total_customers
FROM dim_customers
GROUP BY country
ORDER BY total_customers DESC;

-------------------------------------------------

/* Find total customers by gender */

SELECT
    gender,
    COUNT(customer_key) AS total_customers
FROM dim_customers
GROUP BY gender
ORDER BY total_customers DESC;

-------------------------------------------------

/* Find total products by category */

SELECT
    category,
    COUNT(product_number) AS total_products
FROM dim_product
GROUP BY category
ORDER BY total_products DESC;

-------------------------------------------------

/* Find average cost in each category */

SELECT
    category,
    AVG(product_cost) AS avg_cost
FROM dim_product
GROUP BY category
ORDER BY avg_cost;

-------------------------------------------------

/* Total revenue generated by each category */

SELECT
    p.category,
    SUM(f.sales_amount) AS total_revenue
FROM fact_sales f
LEFT JOIN dim_product p
ON p.product_key = f.product_key
GROUP BY p.category
ORDER BY total_revenue DESC;

-------------------------------------------------

/* Total revenue generated by each customer */

SELECT
    c.customer_id,
    c.first_name,
    c.last_name,
    SUM(f.sales_amount) AS total_revenue
FROM fact_sales f
LEFT JOIN dim_customers c
ON f.customer_key = c.customer_key
GROUP BY
    c.customer_id,
    c.first_name,
    c.last_name
ORDER BY total_revenue DESC;

-------------------------------------------------

/* Distribution of items sold across countries */

SELECT
    c.country,*    SUM(f.quantity) AS total_sold_*tems
FROM fact_sales f
LEFT JOIN d*m_customers c
ON f.customer_key = *.customer_key
GROUP BY c.country
O*DER BY total_sold_items DESC;
